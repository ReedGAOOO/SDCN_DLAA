"""
Run SDCN_DLAA on a labeled conceptual dataset directory and emit a small summary JSON.

Expected files in `--data_dir` (generated by tools/generate_conceptual_data.py):
- node_features.npy
- labels.npy
- binary_adj.npz
- edge_attr.npy
"""

